#!/usr/bin/env node
/**
 * Generate per-package BUILD.bazel files and //javascript:build aggregate.
 * Run from repo root: node tools/bazel/generate-js-builds.mjs
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '../..');
const workspaceRoots = ['apps', 'packages', 'infra', 'demos'];

const isWorkspaceDep = (version) => typeof version === 'string' && version.startsWith('workspace:');

async function listPackageDirs() {
  const dirs = [];
  for (const root of workspaceRoots) {
    const absRoot = path.join(repoRoot, root);
    let entries;
    try {
      entries = await readdir(absRoot, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (!entry.isDirectory()) {
        continue;
      }
      const pkgDir = path.join(absRoot, entry.name);
      const pkgJsonPath = path.join(pkgDir, 'package.json');
      try {
        await readFile(pkgJsonPath, 'utf8');
        dirs.push(path.relative(repoRoot, pkgDir));
      } catch {
        // skip
      }
    }
  }
  return dirs.sort();
}

async function readPackageJson(pkgDir) {
  const raw = await readFile(path.join(repoRoot, pkgDir, 'package.json'), 'utf8');
  return JSON.parse(raw);
}

function bazelLabel(pkgDir) {
  return `//${pkgDir.replaceAll(path.sep, '/')}:build`;
}

function collectWorkspaceDeps(pkgJson) {
  const names = new Set();
  for (const section of ['dependencies', 'devDependencies', 'peerDependencies']) {
    const deps = pkgJson[section];
    if (!deps) {
      continue;
    }
    for (const [name, version] of Object.entries(deps)) {
      if (isWorkspaceDep(version)) {
        names.add(name);
      }
    }
  }
  return [...names].sort();
}

function formatBuildFile({ macro, deps }) {
  const lines = ['load("//tools/bazel:js_package.bzl", "' + macro + '")', ''];
  if (deps.length === 0) {
    lines.push(`${macro}()`);
  } else {
    lines.push(`${macro}(`);
    lines.push('    deps = [');
    for (const dep of deps) {
      lines.push(`        "${dep}",`);
    }
    lines.push('    ],');
    lines.push(')');
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const pkgDirs = await listPackageDirs();
  const packages = new Map();

  for (const pkgDir of pkgDirs) {
    const pkgJson = await readPackageJson(pkgDir);
    const scripts = pkgJson.scripts ?? {};
    packages.set(pkgJson.name, {
      pkgDir,
      hasBuild: typeof scripts.build === 'string',
      hasTest: typeof scripts.test === 'string'
    });
  }

  const buildTargets = [];

  for (const pkgDir of pkgDirs) {
    const pkgJson = await readPackageJson(pkgDir);
    const scripts = pkgJson.scripts ?? {};
    const workspaceDeps = collectWorkspaceDeps(pkgJson);
    const depLabels = workspaceDeps
      .map((name) => packages.get(name))
      .filter((info) => info?.hasBuild)
      .map((info) => bazelLabel(info.pkgDir));

    if (scripts.build) {
      const content = formatBuildFile({ macro: 'js_npm_package', deps: depLabels });
      await writeFile(path.join(repoRoot, pkgDir, 'BUILD.bazel'), content);
      buildTargets.push(bazelLabel(pkgDir));
    } else if (scripts.test) {
      const content = formatBuildFile({ macro: 'js_npm_test', deps: depLabels });
      await writeFile(path.join(repoRoot, pkgDir, 'BUILD.bazel'), content);
    }
  }

  const aggregate = `\
# Aggregate JavaScript build/test targets (generated by tools/bazel/generate-js-builds.mjs).

package(default_visibility = ["//visibility:public"])

_BUILD_TARGETS = [
${buildTargets.map((t) => `    "${t}",`).join('\n')}
]

genrule(
    name = "build",
    srcs = _BUILD_TARGETS,
    outs = ["build.stamp"],
    cmd = "touch \\"$@\\"",
)

genrule(
    name = "test",
    srcs = ["//packages/leetcode:test"],
    outs = ["test.stamp"],
    cmd = "touch \\"$@\\"",
)
`;

  await writeFile(path.join(repoRoot, 'javascript/BUILD.bazel'), aggregate);
  console.log(`Generated ${buildTargets.length} build targets.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
